import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { randomUUID } from 'node:crypto';
import { inspect as inspectError } from 'node:util';
import { createServer } from 'node:http';
import { createServer as reservePort } from 'node:net';
import { Context } from '@deepseek-ai/cordis';
import { SessionStore, SessionId } from '@deepseek-ai/dsh-session';
import AgentRegistry from '@deepseek-ai/dsh-agent';
import AgentLoop from '@deepseek-ai/dsh-agent-loop';
import LlmRuntime from '@deepseek-ai/dsh-llm';
import SystemPrompt from '@deepseek-ai/dsh-system-prompt';
import ToolRuntime from '@deepseek-ai/dsh-tools';
import SessionProjections from '@deepseek-ai/dsh-session-projection';
import LocalFileSystem from '@deepseek-ai/dsh-fs-local';
import WorkingDirectory from '@deepseek-ai/dsh-working-directory';
import * as ShellEnv from '@deepseek-ai/dsh-shell-env';
import PwshLocal from '@deepseek-ai/dsh-pwsh-local';
import SubprocessLocal from '@deepseek-ai/dsh-subprocess-local';
import { RedTeamStore } from '../lib/store.js';
import { TrafficRuntime } from '../lib/traffic.js';
import { installTrafficEnvironment } from '../lib/traffic-tools/environment.js';

test('official pwsh tool routes only the bound worker through the capture proxy without global env mutation', { timeout: 60_000, skip: process.platform !== 'win32' }, async t => {
  const dir = await mkdtemp(join(tmpdir(), 'traffic-shell-'));
  const app = new Context(), fibers = [], agents = [];
  const store = new RedTeamStore(join(dir,'state.json'));
  const runtime = new TrafficRuntime(store);
  const target = createServer((_request,response) => response.end('native shell routed'));
  const targetSockets = new Set();
  target.on('connection', socket => { targetSockets.add(socket); socket.on('close', () => targetSockets.delete(socket)); });
  const cleanupTrace = stage => { if (process.env.DSH_TEST_CLEANUP_TRACE) process.stderr.write(`traffic environment cleanup: ${stage}\n`); };
  t.after(async () => {
    const errors = [];
    const cleanup = async (stage, action) => {
      cleanupTrace(stage);
      try { await action(); } catch (error) { errors.push(error); }
    };
    cleanupTrace('target connections');
    for (const socket of targetSockets) socket.destroy();
    await cleanup('runtime.stop', () => runtime.stop());
    for (const handle of agents.reverse()) await cleanup('agents.dispose', () => handle.dispose());
    for (const fiber of fibers.reverse()) await cleanup('fibers.dispose', () => fiber.dispose());
    await cleanup('target.close', () => new Promise(resolve => target.close(resolve)));
    await cleanup('remove temp', () => rm(dir,{recursive:true,force:true}));
    cleanupTrace('complete');
    if (errors.length) throw new AggregateError(errors, 'traffic environment cleanup failed');
  });
  const mount = async (module,config) => { fibers.push(await app.plugin(module,config)); };
  await mount(SessionStore); await mount(AgentRegistry); await mount(SystemPrompt,{}); await mount(ToolRuntime,{mode:'native'});
  await mount(LlmRuntime); await mount(AgentLoop);
  await mount(SessionProjections); await mount(LocalFileSystem,{cwd:dir}); await mount(WorkingDirectory,{defaultDirectory:dir});
  await mount(ShellEnv,{}); await mount(SubprocessLocal,{}); await mount(PwshLocal,{cwd:dir});
  await mount(ctx => installTrafficEnvironment(ctx,store,runtime));
  const makeAgent = async () => { const handle = await app.get('agents').create({sessionId:SessionId(randomUUID()),meta:{cwd:dir}}); agents.push(handle); return handle.agent; };
  const parent = await makeAgent(), child = await makeAgent(), unrelated = await makeAgent();
  const task = await store.createTask('Shell routing','Use capture only for its bound worker');
  const other = await store.createTask('Other task','No capture environment');
  await store.addIntent({taskId:task.id,summary:'Worker',input:{},execution:{childSessionId:child.id,parentSessionId:parent.id,provider:'spawn'}});
  await store.addIntent({taskId:other.id,summary:'Other worker',input:{},execution:{childSessionId:unrelated.id,parentSessionId:parent.id,provider:'spawn'}});
  await new Promise(resolve => target.listen(0,'127.0.0.1',resolve));
  const reservation = reservePort(); await new Promise(resolve => reservation.listen(0,'127.0.0.1',resolve));
  const port = reservation.address().port; await new Promise(resolve => reservation.close(resolve));
  const initialEnvironment = {...process.env};
  const started = await runtime.start(task.id,port,{workerSessionId:child.id}).catch(error => {
    t.diagnostic(inspectError(error, {depth: 8}));
    throw error;
  });
  const call = async (agent,command) => {
    const result = await app.get('tools').execute({callId:randomUUID(),name:'pwsh',arguments:{description:'Verify task-specific shell environment',command},agent,signal:AbortSignal.timeout(15000)});
    assert.equal(result.isError,false,JSON.stringify(result));
    assert.equal(result.value.exitCode,0,JSON.stringify(result.value));
    return result.value.stdout.text.trim();
  };
  const inspect = '[ordered]@{proxy=$env:HTTP_PROXY;ca=$env:SSL_CERT_FILE;session=$env:DSH_SESSION_ID}|ConvertTo-Json -Compress';
  const [parentEnv,childEnv,otherEnv] = await Promise.all([parent,child,unrelated].map(async agent => JSON.parse(await call(agent,inspect))));
  assert.equal(childEnv.proxy,started.proxyUrl); assert.equal(childEnv.ca,started.caCertPath); assert.equal(childEnv.session,child.id);
  assert.notEqual(parentEnv.proxy,started.proxyUrl); assert.notEqual(otherEnv.proxy,started.proxyUrl);
  const source = `fetch('http://127.0.0.1:${target.address().port}/shell').then(r=>r.text()).then(console.log).catch(e=>{console.error(e);process.exitCode=1})`;
  const command = `$env:NO_PROXY=''; $env:no_proxy=''; & '${process.execPath.replaceAll("'","''")}' -e '${source.replaceAll("'","''")}'`;
  assert.equal(await call(child,command),'native shell routed');
  await runtime.stop();
  assert.equal(store.snapshot().traffic.filter(row=>row.url.endsWith('/shell') && row.workerSessionId===child.id).length,1);
  assert.notEqual(JSON.parse(await call(child,inspect)).proxy,started.proxyUrl,'stopped capture does not leak stale proxy settings');
  assert.deepEqual({...process.env},initialEnvironment);
});
