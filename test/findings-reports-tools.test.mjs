import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { mkdtemp,rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { Context } from '@deepseek-ai/cordis';
import ToolRuntime from '@deepseek-ai/dsh-tools';
import SystemPrompt from '@deepseek-ai/dsh-system-prompt';
import { RedTeamStore } from '../lib/store.js';
import { installFindingsReportTools } from '../lib/findings-reports/index.js';

test('actual DSH registry executes recording, status, filtering, exact selection, report and evidence errors',async t=>{
  const dir=await mkdtemp(join(tmpdir(),'finding-tools-')),store=new RedTeamStore(join(dir,'state.json'));
  const task=await store.createTask('工具验收','目标'),other=await store.createTask('其他','目标');
  const app=new Context(),prompt=await app.plugin(SystemPrompt,{}),tools=await app.plugin(ToolRuntime,{mode:'native'});
  let installation;
  const plugin=await app.plugin({inject:['tools'],apply:ctx=>{installation=installFindingsReportTools(ctx,store,{reportProvider:{generate:async({finding})=>`# ${finding.name}\n\n${finding.summary}`},resolveAccess:()=>({taskId:task.id})});}});
  t.after(async()=>{installation.dispose();await plugin.dispose();await tools.dispose();await prompt.dispose();await rm(dir,{recursive:true,force:true});});
  const invoke=(name,args)=>app.get('tools').execute({callId:randomUUID(),name,arguments:args,signal:AbortSignal.timeout(10000)});
  const call=async(name,args)=>{const result=await invoke(name,args);assert.equal(result.isError,false,JSON.stringify(result));return result.value;};
  const f=await call('redteam_record_finding',{task_id:task.id,vuln_class:'SQLi',severity:'high',summary:'输出证据',name:'实际发现'});
  assert.match(f.report,/实际发现/);
  await call('redteam_finding_record',{task_id:task.id,vuln_class:'XSS',severity:'low',summary:'另一个'});
  assert.equal((await call('redteam_finding_query',{action:'list',filter:{vulnClass:'SQLi'}})).total,1);
  assert.deepEqual(await call('redteam_finding_query',{action:'classes'}),['SQLi','XSS']);
  await call('redteam_update_finding',{finding_id:f.id,status:'confirmed'});
  const report=await call('redteam_finding_report',{finding_id:f.id,action:'generate'});assert.match(report.report,/实际发现/);
  const exported=await call('redteam_finding_export',{scope:'selected',ids:[f.id],filter:{severity:'low'},format:'json'});
  const parsed=JSON.parse(Buffer.from(exported.base64,'base64').toString());assert.equal(parsed.length,1);assert.equal(parsed[0].id,f.id);
  const taskReport=await call('redteam_task_report',{task_id:task.id});assert.match(taskReport.markdown,/工具验收/);assert.equal(taskReport.version,1);
  assert.equal((await invoke('redteam_finding_record',{task_id:other.id,vuln_class:'x',severity:'high',summary:'x'})).isError,true);
  assert.equal((await invoke('redteam_record_finding',{task_id:other.id,vuln_class:'x',severity:'high',summary:'x'})).isError,true);
  const foreign=await store.addFinding({taskId:other.id,vulnClass:'x',severity:'low',summary:'foreign',evidenceIds:[],assetIds:[],status:'pending'});
  assert.equal((await invoke('redteam_update_finding',{finding_id:foreign.id,status:'fixed'})).isError,true);
  assert.equal((await invoke('redteam_finding_export',{scope:'selected',ids:[],format:'json'})).isError,true);
  assert.equal((await invoke('redteam_finding_traffic',{finding_id:f.id,action:'edit',binding_id:'x'})).isError,true);
  assert.equal((await invoke('redteam_finding_traffic',{finding_id:f.id,action:'bind',traffic_refs:[{traffic_id:'unverified'}]})).isError,true);
  assert.equal((await invoke('redteam_finding_deepen',{finding_id:f.id,description:'follow up'})).isError,true);
  assert.equal(store.snapshot().notificationEvents.length,4);
});
