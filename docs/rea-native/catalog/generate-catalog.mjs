function location(files, pattern) {
  return files.flatMap(file => {
    const index = file.text.search(pattern);
    return index < 0 ? [] : [{ file: file.path, line: file.text.slice(0, index).split('\n').length, sha256: createHash('sha256').update(file.text).digest('hex') }];
  });
}
